"""Explanation Stability Research Module for RootIQ.

Evaluates how explanations generated by SHAP and LIME behave under
controlled, physically bounded input perturbations and stochastic seed variations.
"""

import logging
from typing import Dict, Any, List, Tuple, Optional
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from src.config import (
    RANDOM_SEED,
    FEATURE_CONSTRAINTS,
    PERTURBATION_EPSILONS,
    NUMERICAL_COLS
)

logger = logging.getLogger(__name__)


def apply_controlled_perturbation(
    instance_dict: Dict[str, Any],
    epsilon: float,
    random_state: Optional[int] = None,
    noise_type: str = "uniform"
) -> Tuple[Dict[str, Any], Dict[str, float]]:
    """Apply controlled relative perturbation to continuous features within physical bounds.
    
    Formula:
        x_perturbed = x_original + delta
        where delta ~ Uniform(-epsilon * span, +epsilon * span) or Normal(0, epsilon * span)
        span = physical_max - physical_min
    
    Any perturbed feature falling outside physical machine constraints is clipped
    to prevent physically impossible operating states (e.g. negative rotational speed).
    """
    rng = np.random.RandomState(random_state)
    perturbed = dict(instance_dict)
    applied_deltas = {}

    for feature_name, val in instance_dict.items():
        if feature_name in FEATURE_CONSTRAINTS and "min" in FEATURE_CONSTRAINTS[feature_name]:
            constraints = FEATURE_CONSTRAINTS[feature_name]
            f_min = constraints["min"]
            f_max = constraints["max"]
            span = f_max - f_min

            if noise_type == "uniform":
                delta = rng.uniform(-epsilon * span, epsilon * span)
            else:
                delta = rng.normal(0, epsilon * span / 2.0)

            new_val = val + delta
            
            # Constrain to realistic domain operating envelope (Clipping decision)
            clipped_val = float(np.clip(new_val, f_min, f_max))
            actual_delta = clipped_val - val
            
            perturbed[feature_name] = round(clipped_val, 3)
            applied_deltas[feature_name] = round(actual_delta, 3)

    return perturbed, applied_deltas


def compute_explanation_stability_metrics(
    raw_vector_orig: np.ndarray,
    raw_vector_pert: np.ndarray,
    feature_names: List[str],
    top_k: int = 3
) -> Dict[str, float]:
    """Compute stability metrics between base and perturbed explanation vectors:
    1. Spearman Rank Correlation (rho)
    2. Top-k Jaccard Feature Overlap
    3. Normalized Vector Cosine Similarity
    4. Mean Absolute Difference (L1 shift)
    """
    abs_orig = np.abs(raw_vector_orig)
    abs_pert = np.abs(raw_vector_pert)

    # 1. Spearman Rank Correlation
    if np.all(abs_orig == 0) or np.all(abs_pert == 0):
        spearman_rho = 0.0
    else:
        corr_res = spearmanr(abs_orig, abs_pert)
        spearman_rho = float(corr_res.correlation) if not np.isnan(corr_res.correlation) else 0.0

    # 2. Top-k Feature Overlap
    rank_orig_idx = np.argsort(abs_orig)[::-1][:top_k]
    rank_pert_idx = np.argsort(abs_pert)[::-1][:top_k]

    set_orig = set([feature_names[i] for i in rank_orig_idx])
    set_pert = set([feature_names[i] for i in rank_pert_idx])

    intersection = set_orig.intersection(set_pert)
    union = set_orig.union(set_pert)
    top_k_jaccard = float(len(intersection) / len(union)) if len(union) > 0 else 0.0

    # 3. Normalized Vector Cosine Similarity
    norm_orig = np.linalg.norm(raw_vector_orig)
    norm_pert = np.linalg.norm(raw_vector_pert)
    if norm_orig > 1e-12 and norm_pert > 1e-12:
        cosine_sim = float(np.dot(raw_vector_orig, raw_vector_pert) / (norm_orig * norm_pert))
    else:
        cosine_sim = 1.0 if (norm_orig <= 1e-12 and norm_pert <= 1e-12) else 0.0

    # 4. Normalized L1 Attribution Shift
    sum_orig = np.sum(abs_orig) + 1e-12
    sum_pert = np.sum(abs_pert) + 1e-12
    norm_l1_orig = abs_orig / sum_orig
    norm_l1_pert = abs_pert / sum_pert
    l1_shift = float(np.mean(np.abs(norm_l1_orig - norm_l1_pert)))

    return {
        "spearman_correlation": round(spearman_rho, 4),
        f"top_{top_k}_jaccard": round(top_k_jaccard, 4),
        "cosine_similarity": round(cosine_sim, 4),
        "attribution_l1_shift": round(l1_shift, 4)
    }


class ExplanationStabilityStudy:
    """Manages perturbation study and LIME seed stochasticity experiment."""

    def __init__(
        self,
        shap_explainer: Any,
        lime_explainer: Any,
        preprocessor: Any,
        feature_names: List[str]
    ):
        self.shap_explainer = shap_explainer
        self.lime_explainer = lime_explainer
        self.preprocessor = preprocessor
        self.feature_names = feature_names

    def run_perturbation_study(
        self,
        test_samples_df: pd.DataFrame,
        epsilons: List[float] = PERTURBATION_EPSILONS,
        random_seed: int = RANDOM_SEED
    ) -> Dict[str, Any]:
        """Evaluate explanation stability across multiple held-out test observations
        at various perturbation magnitudes for both SHAP and LIME.
        """
        results_by_epsilon = {
            eps: {"SHAP": [], "LIME": []} for eps in epsilons
        }

        logger.info(f"Running perturbation study on {len(test_samples_df)} test samples across epsilons: {epsilons}")

        for idx, (_, row) in enumerate(test_samples_df.iterrows()):
            instance_dict = row.to_dict()
            
            # Base transformed array
            row_df = pd.DataFrame([instance_dict])
            X_base = self.preprocessor.transform(row_df)[0]
            
            # Base explanations
            base_shap = self.shap_explainer.explain_instance(X_base)
            base_lime = self.lime_explainer.explain_instance(X_base, num_samples=500, random_seed=random_seed)

            for eps in epsilons:
                pert_dict, _ = apply_controlled_perturbation(
                    instance_dict,
                    epsilon=eps,
                    random_state=random_seed + idx
                )
                pert_df = pd.DataFrame([pert_dict])
                X_pert = self.preprocessor.transform(pert_df)[0]

                # Perturbed explanations
                pert_shap = self.shap_explainer.explain_instance(X_pert)
                pert_lime = self.lime_explainer.explain_instance(X_pert, num_samples=500, random_seed=random_seed)

                # Compute metrics
                m_shap = compute_explanation_stability_metrics(
                    base_shap["raw_vector"],
                    pert_shap["raw_vector"],
                    self.feature_names
                )
                m_lime = compute_explanation_stability_metrics(
                    base_lime["raw_vector"],
                    pert_lime["raw_vector"],
                    self.feature_names
                )

                results_by_epsilon[eps]["SHAP"].append(m_shap)
                results_by_epsilon[eps]["LIME"].append(m_lime)

        # Aggregate summary table
        summary = {}
        for eps in epsilons:
            summary[str(eps)] = {}
            for method in ["SHAP", "LIME"]:
                metrics_list = results_by_epsilon[eps][method]
                summary[str(eps)][method] = {
                    "mean_spearman": round(float(np.mean([m["spearman_correlation"] for m in metrics_list])), 4),
                    "std_spearman": round(float(np.std([m["spearman_correlation"] for m in metrics_list])), 4),
                    "mean_top3_jaccard": round(float(np.mean([m["top_3_jaccard"] for m in metrics_list])), 4),
                    "std_top3_jaccard": round(float(np.std([m["top_3_jaccard"] for m in metrics_list])), 4),
                    "mean_cosine_sim": round(float(np.mean([m["cosine_similarity"] for m in metrics_list])), 4),
                    "std_cosine_sim": round(float(np.std([m["cosine_similarity"] for m in metrics_list])), 4),
                    "mean_l1_shift": round(float(np.mean([m["attribution_l1_shift"] for m in metrics_list])), 4)
                }

        return {
            "epsilons": epsilons,
            "sample_size": len(test_samples_df),
            "summary": summary,
            "detailed_records": results_by_epsilon
        }

    def run_lime_seed_sensitivity_study(
        self,
        test_samples_df: pd.DataFrame,
        seeds: List[int] = [10, 42, 99, 123, 777]
    ) -> Dict[str, Any]:
        """Investigate stochastic seed sensitivity of LIME explanations for fixed observations."""
        logger.info(f"Running LIME seed sensitivity study across {len(seeds)} random seeds...")
        
        sample_variance_results = []
        for idx, (_, row) in enumerate(test_samples_df.iterrows()):
            instance_dict = row.to_dict()
            X_inst = self.preprocessor.transform(pd.DataFrame([instance_dict]))[0]

            vectors = []
            for s in seeds:
                exp = self.lime_explainer.explain_instance(X_inst, num_samples=500, random_seed=s)
                vectors.append(exp["raw_vector"])
                
            vectors = np.array(vectors)  # Shape (n_seeds, n_features)
            
            # Pairwise Spearman correlations between different seeds
            pairwise_corrs = []
            for i in range(len(seeds)):
                for j in range(i + 1, len(seeds)):
                    corr = spearmanr(np.abs(vectors[i]), np.abs(vectors[j])).correlation
                    if not np.isnan(corr):
                        pairwise_corrs.append(corr)

            feature_stds = np.std(vectors, axis=0)
            avg_feature_std = float(np.mean(feature_stds))

            sample_variance_results.append({
                "sample_index": idx,
                "pairwise_spearman_mean": round(float(np.mean(pairwise_corrs)) if pairwise_corrs else 1.0, 4),
                "pairwise_spearman_std": round(float(np.std(pairwise_corrs)) if pairwise_corrs else 0.0, 4),
                "avg_attribution_std": round(avg_feature_std, 4),
                "max_attribution_std": round(float(np.max(feature_stds)), 4)
            })

        overall_mean_corr = float(np.mean([r["pairwise_spearman_mean"] for r in sample_variance_results]))
        overall_std_corr = float(np.std([r["pairwise_spearman_mean"] for r in sample_variance_results]))

        return {
            "seeds_tested": seeds,
            "overall_mean_seed_correlation": round(overall_mean_corr, 4),
            "overall_std_seed_correlation": round(overall_std_corr, 4),
            "sample_results": sample_variance_results
        }
